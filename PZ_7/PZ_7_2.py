# 2. Дана строка, содержащая полное имя файла.
#    Выделить из этой строки название последнего каталога (без символов «\»).
#    Если файл содержится в корневом каталоге, то вывести символ «\».

try:
    path = input("Введите полный путь к файлу: ")

    # Убираем имя файла (последнюю часть после последнего \)
    if '\\' in path:
        # Разделяем путь по обратным слешам
        parts = path.rstrip('\\').split('\\')
        # Убираем последнюю часть (имя файла)
        parts = parts[:-1]

        if parts:
            # Берём последний каталог
            last_dir = parts[-1]
            print("Последний каталог:", last_dir)
        else:
            # Файл в корневом каталоге
            print("\\")
    else:
        # Нет слешей - файл в текущем каталоге или корневом
        print("\\")

except Exception as e:
    print("Ошибка:", e)